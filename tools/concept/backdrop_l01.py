def save(img, name, size):
    if img.size != size:
        raise ValueError(f"{name}: rendered {img.size}, the data file says {size}")
    info = PngInfo()
    info.add_text("Placeholder", NOTE)
    img.save(OUT / f"{name}.png", pnginfo=info, optimize=True)


def main():
    backdrop = yaml.safe_load(LEVEL.read_text(encoding="utf-8"))["backdrop"]
    wanted = set(sys.argv[1:])
    unknown = wanted - TILE_SETS.keys() - PIECES.keys()
    if unknown or backdrop["tile_sets"].keys() - TILE_SETS.keys() or backdrop["pieces"].keys() - PIECES.keys():
        raise SystemExit(f"no generator for {sorted(unknown) or 'a tile set or piece of the data file'}")
    OUT.mkdir(parents=True, exist_ok=True)
    width = 480
    for name, spec in backdrop["tile_sets"].items():
        if not wanted or name in wanted:
            save(TILE_SETS[name](width, spec["height"]), name, (width, spec["height"]))
            print("tile set", name)
    for name, spec in backdrop["pieces"].items():
        if wanted and name not in wanted:
            continue
        w, h = spec["size"]
        count = spec.get("frames") or spec.get("headings")
        if count:
            for i, img in enumerate(PIECES[name](w, h, count)):
                save(img, f"{name}_{i}", (w, h))
        else:
            save(PIECES[name](w, h), name, (w, h))
        print("piece", name)


if __name__ == "__main__":
    main()
