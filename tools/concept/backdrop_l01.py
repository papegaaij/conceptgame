def platform_model(damaged):
    """A CDF defence platform: deck ring, gun dome, sensor mast, two short array wings."""
    def scene(p):
        q = mirror_x(p)
        d, m = union((sd_cylinder_z(p, (0, 0, 0), 40, 4), HULL),
                     (sd_cylinder_z(p, (0, 0, 4), 30, 1.5), DARK),
                     (sd_sphere(p, (0, 0, 2), 18), HULL),
                     (sd_capsule(p, (-4, 6, 12), (-4, 30, 12), 2.4), DARK),
                     (sd_capsule(p, (4, 6, 12), (4, 30, 12), 2.4), DARK),
                     (sd_box(q, (54, 0, 0), (16, 20, 1), 0.3), SOLAR),
                     (sd_sphere(q, (40, 0, 4), 2.5), RED), k=1.5)
        if damaged:   # blown-out deck sections and a broken wing
            for c, r in (((-22, -18, 4), 12), ((20, 20, 4), 10), ((58, -8, 0), 14)):
                d = np.maximum(d, -sd_sphere(p, c, r))
        return d, m
    return scene


