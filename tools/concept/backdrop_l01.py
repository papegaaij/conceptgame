def cruiser_hull(w, h):
    """The half-built cruiser: plated stern, bare ribs and keel towards the bow, side scaffolds."""
    length, radius = h - 40, 58
    top = length / 2 - radius

    def scene(p):
        shell = sd_capsule(p, (0, -top, 0), (0, top, 0), radius)
        plated = np.maximum(shell, p[:, 1] - 20)
        slabs = np.abs((p[:, 1] % 26) - 13) - 3.5
        ribs = np.maximum(np.maximum(np.abs(shell) - 4.0, slabs), 20 - p[:, 1])
        return union((plated, HULL),
                     (ribs, DARK),
                     (sd_box(p, (0, top / 2 + 10, -radius * 0.55), (5, top / 2, 5), 1), DARK),
                     (sd_box(p, (0, -top * 0.4, radius - 3), (12, 30, 6), 1.5), DARK),
                     (sd_cylinder_y(mirror_x(p), (22, -top - radius, -6), 14, 10), ACCENT),
                     (sd_box(p, (0, 10, radius - 2), (radius * 0.7, 3, 2.5), 0.8), WARM))
    hull = part(scene, (radius * 2 + 8, h), factor=3, colors=48)
    k = kit()
    low = blank(w, h)
    for x in (18, w - 18):
        column(low, k["truss_v"], x, 10, h - 10)
    for y in (70, 230, 390):
        put(low, truss_h(w - 30, 20), w / 2, y)
    high = blank(w, h)
    put(high, hull, w / 2, h / 2)
    return with_shadow(low, high)


