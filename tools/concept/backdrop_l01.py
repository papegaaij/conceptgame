def earth_tile(w, h):
    """The day side far below, light weather: r02's Earth with fewer, thinner clouds."""
    earth = terrain.earth_coast(w, h, seed=11, period=True, cell=128,
                                stops=terrain.coast_stops_from(SEA, LAND, 0.56))
    e = np.array(earth).astype(np.float64)
    clouds = raster.fbm(w, h, 64, 61, octaves=5, period=True)
    c = np.clip((clouds - 0.6) * 2.4, 0, 0.8)[..., None]
    e[..., :3] = e[..., :3] * (1 - c) + np.array(SEA[5]) * c
    e[..., :3] *= 1 - 0.3 * np.roll(np.roll(c, 4, axis=0), 4, axis=1) * (1 - c)
    grey = e[..., :3].mean(axis=-1, keepdims=True)
    e[..., :3] = (e[..., :3] * 0.6 + grey * 0.4) * 0.5 + np.array(SEA[1]) * 0.5
    return posterize(rgba(e[..., :3], e[..., 3]), 20)


def limb_layer(w, h, inside, depth, seed):
    """Space and the atmosphere rim around Earth's limb, as an overlay on the earth tiles.
    ``inside``: Earth mask; ``depth``: px from the limb (positive inside)."""
    arr = np.zeros((h, w, 4))
    st = stars(w, h, seed)
    arr[~inside, :3] = st[~inside, :3]
    arr[~inside, 3] = 1
    rim = np.array(SEA[4], float)
    glow_out = np.exp(depth / 5.0) * (~inside)           # thin blue atmosphere beyond the limb
    over(arr, rim * 0.8, glow_out * 0.85)
    glow_in = np.exp(-depth / 7.0) * inside               # the limb brightening
    over(arr, rim, glow_in * 0.45)
    return arr


def earth_dawn(w, h):
    """Section 1-2 over the earth tiles: space and the Moon's side bottom-left, Earth's curve,
    the night side with city lights and the sunrise terminator; transparent over the day side.
    Earth covers the whole top edge and the overlay fades out over the top 24 rows, so no edge
    shows when the top scrolls down the screen."""
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float64)
    depth = 1510 - np.hypot(xx - 1455, yy - 400)
    inside = depth > 0
    arr = limb_layer(w, h, inside, depth, 9)
    line = yy - (1150 + 0.25 * xx)                          # the terminator, day above it
    night = sdf.smoothstep(-40, 60, line) * inside
    over(arr, np.array(SEA[0], float) + 6, night * 0.72)
    rng = np.random.default_rng(21)
    towns = raster.fbm(w, h, 32, 23, octaves=3, period=False)
    lights = (towns > 0.62) & (rng.random((h, w)) < 0.05) & (night > 0.5)
    over(arr, np.array([210, 180, 120], float), lights * 0.9)
    band = np.exp(-(line / 38.0) ** 2) * inside            # dawn light along the terminator
    over(arr, np.array([200, 150, 100], float), band * 0.28)
    arr[..., 3] *= np.clip(yy / 24, 0, 1)
    return finish(arr)


def earth_limb(w, h, radius=520, below=240, haze_depth=110):
    """Section 5 over the earth tiles: Earth's curve falling behind (a circle whose crest is
    ``below`` px above the bottom edge). Towards the limb the day side hazes into the atmosphere
    colour and darkens over ``haze_depth`` px (the view grazes more air); the atmosphere is a
    thin bright rim, lit a little more towards the key light at the left; beyond it a faint
    airglow fades into open space, whose stars thin out near the rim. Transparent at the bottom
    edge; the opaque top edge stays above the screen until the debrief, after the outro."""
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float64)
    crest = h - below
    depth = radius - np.hypot(xx - w * 0.58, yy - crest - radius)   # px inside the limb
    inside = np.clip(depth + 0.5, 0, 1)                              # 1 px anti-aliased edge
    arr = np.zeros((h, w, 4))
    graze = np.clip(1 - depth / haze_depth, 0, 1) ** 2
    over(arr, np.array(SEA[2], float) * (1 - 0.4 * graze)[..., None], 0.85 * graze * inside)
    st = stars(w, h, 13)
    space = st[..., :3] * np.clip(-depth / 60, 0, 1)[..., None]
    over(arr, space, 1 - inside)
    over(arr, np.array(SEA[3], float) * 0.7, 0.3 * np.exp(np.minimum(depth, 0) / 16) * (1 - inside))
    light = 0.8 + 0.2 * (1 - xx / w)
    over(arr, np.array(SEA[4], float), 0.9 * light * np.exp(-((depth + 1) / 2.2) ** 2))
    over(arr, np.array(SEA[5], float), 0.6 * light * np.exp(-((depth + 1) / 1.0) ** 2))
    return finish(arr, colors=32, alpha_levels=24)


def moon(w, h):
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float64)
    r = w / 2 - 1
    dx, dy = (xx - w / 2 + 0.5) / r, (yy - h / 2 + 0.5) / r
    d2 = dx * dx + dy * dy
    nz = np.sqrt(np.clip(1 - d2, 0, 1))
    lit = np.clip(-0.55 * dx - 0.6 * dy + 0.6 * nz, 0, 1)    # key light from the top-left
    craters = raster.fbm(w, h, 6, 31, octaves=3, period=False)
    rgb = np.array([150, 155, 170], float) * (0.25 + 0.85 * lit * (0.8 + 0.3 * craters))[..., None]
    img = haze(rgba(rgb, (d2 <= 1) * 255), SEA[2], 0.25)
    return posterize(img, 10)


def vrell_glow(w, h):
    """The strike group's glow on the horizon (top edge), violet into teal, kept dim; the top
    edge stays above the screen until the debrief."""
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float64)
    n = raster.fbm(w, h, 40, 41, octaves=4, period=False)
    mix = np.clip(raster.fbm(w, h, 120, 43, octaves=2, period=False) * 1.4 - 0.2, 0, 1)[..., None]
    rgb = np.array([96, 20, 128], float) * (1 - mix) + np.array([0, 140, 100], float) * mix
    a = (1 - yy / h) ** 2.2 * (0.25 + 0.3 * n)
    arr = np.dstack([rgb, a])
    rng = np.random.default_rng(45)
    for _ in range(14):                                     # distant ship lights
        x, y = int(rng.uniform(20, w - 20)), int(rng.uniform(6, 48))
        arr[y, x] = (120, 255, 200, 0.85)
    return finish(arr, 20)


