def lattice_beam(w, h):
    img = blank(w, h)
    put(img, truss_h(w, 30), w / 2, h / 2)
    return img


def crane_jib(w, h):
    """A tower crane's jib: a truss arm with a counterweight at the left and the hook at the right."""
    def scene(p):
        return union((sd_box(p, (-w / 2 + 24, 0, 2), (20, 18, 6), 1.5), DARK),
                     (sd_box(p, (-w / 2 + 24, 0, 8), (14, 12, 1), 0.5), ACCENT),
                     (sd_box(p, (w / 2 - 22, 0, 2), (6, 8, 3), 0.8), HULL),
                     (sd_sphere(p, (w / 2 - 10, 0, 4), 2), RED))
    img = blank(w, h)
    put(img, truss_h(w - 40, 26), w / 2 + 10, h / 2)
    img.alpha_composite(part(scene, (w, h)))
    return img


def banks(w, h, cover_share):
    """Cloud decks covering about ``cover_share`` of the screen (atmosphere intensity), tiling
    in x and y so they can drift; r03's billowy shading, posterized, stepped alpha."""
    n = r03.noise(w, h, [160, 80, 40, 20], 301, gains=[1.0, 0.5, 0.3, 0.15])
    soft = 0.12
    cover = np.quantile(n, 1 - cover_share) - soft / 2
    tones = [tuple(int(c * k + g) for c in SEA[i]) for i, k, g in
             ((1, 0.8, 30), (2, 0.5, 70), (4, 0.5, 100), (5, 0.6, 80))]
    arr = wrap_padded(lambda big: r03.bank(big, cover, soft, tones, max_alpha=235), n)
    img = r03.step_alpha(posterize(Image.fromarray(arr, "RGBA"), 12))
    return r03.OrbitScene._dim(img, 0.85)


def wisps(w, h):
    """Thin wisps for the additive high-air layer (drawn at 40 % opacity)."""
    n = r03.noise(w, h, [96, 48, 24, 12], 311)
    a = np.clip((n - 0.7) * 3.4, 0, 1) ** 1.3 * 150
    return r03.step_alpha(rgba(np.broadcast_to(np.array(SEA[5], float) * 0.9, a.shape + (3,)), a), 10)


def spark_streaks(w, h):
    """Thin spark streaks from the burning platforms, for the additive high-air layer."""
    arr = np.zeros((h, w, 4))
    rng = np.random.default_rng(51)
    for _ in range(46):
        x, y, length = int(rng.uniform(0, w)), int(rng.uniform(0, h)), int(rng.uniform(6, 20))
        for i in range(length):
            arr[(y - i) % h, x] = (235, 205, 150, (1 - i / length) * rng.uniform(0.5, 1.0))
    return rgba(arr[..., :3], arr[..., 3] * 255)


