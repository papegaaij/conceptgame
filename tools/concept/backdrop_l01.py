# --------------------------------------------------------------------------- helpers

def blank(w, h):
    return Image.new("RGBA", (w, h), (0, 0, 0, 0))


def part(scene, size, factor=4, colors=40):
    """Render a kit part (station materials, 1 world unit = 1 px) to a native sprite."""
    return station.render_part((scene, size), KIT_PAL, factor=factor, colors=colors)


def put(img, spr, x, y, period=None):
    """Paste centred at (x, y); with a period, also one period above and below (tiling in y)."""
    for yy in (y,) if period is None else (y - period, y, y + period):
        sprite.paste_center(img, spr, x, yy)


def column(img, spr, x, y0, y1):
    """Stack a part (a truss bay) from y0 to y1."""
    for y in range(int(y0), int(y1), spr.height):
        sprite.paste(img, spr, x - spr.width / 2, y)


def with_shadow(low, high, offset=(6, 8)):
    """Tall parts cast a short shadow (6, 8) onto the parts below them (art direction)."""
    sh = blank(*low.size)
    sh.alpha_composite(sprite.shadow_of(high, opacity=0.45, blur=1.2), offset)
    out = low.copy()
    out.alpha_composite(r03.masked(sh, low))
    out.alpha_composite(high)
    return out


def wrap_padded(fn, n, pad=32):
    """Apply an image filter chain to a field that tiles in x and y without seams at the edges."""
    big = np.pad(n, pad, mode="wrap")
    return np.array(fn(big))[pad:-pad, pad:-pad]


def rgba(rgb, alpha):
    return raster.to_rgba_image(rgb, alpha)


def over(dst, src_rgb, src_a):
    """Composite a float rgb/alpha layer over a float RGBA array (alpha 0..1), in place."""
    a = src_a[..., None]
    out_a = a + dst[..., 3:4] * (1 - a)
    dst[..., :3] = (src_rgb * a + dst[..., :3] * dst[..., 3:4] * (1 - a)) / np.maximum(out_a, 1e-6)
    dst[..., 3:4] = out_a


def finish(arr, colors=24, alpha_levels=10):
    """Float RGBA (alpha 0..1) -> posterized image with stepped alpha (90s translucency)."""
    img = rgba(arr[..., :3], arr[..., 3] * 255)
    return r03.step_alpha(posterize(img, colors), alpha_levels)


def stars(w, h, seed, density=0.0012):
    img = raster.starfield(w, h, seed, density=density)
    a = np.array(img).astype(np.float64)
    a[..., :3] *= 0.8                                    # the deep layer recedes
    return a


